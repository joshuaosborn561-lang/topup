const OFFICIAL = new Set<string>(PROSPEO_INDUSTRIES);
const OFFICIAL_LOWER = new Map<string, string>(PROSPEO_INDUSTRIES.map((name) => [name.toLowerCase(), name]));

/**
 * ICP / getleads names that are not Prospeo's official spelling.
 * Punctuation (`; ` → `, `) is handled in the mapper, not here.
 */
export const PROSPEO_INDUSTRY_ALIASES: Readonly<Record<string, string>> = {
  "Truck Transportation": "Truck and Railroad Transportation",
};

export type ProspeoIndustryMatch = "exact" | "inexact" | "none";

export interface ProspeoIndustryMapping {
  input: string;
  prospeo: string | null;
  match: ProspeoIndustryMatch;
}

function punctuationForm(name: string): string {
  return name.replace(/; /g, ", ");
}

export function mapProspeoIndustry(name: string): ProspeoIndustryMapping {
  const input = name.trim();
  if (!input) return { input: name, prospeo: null, match: "none" };
  if (OFFICIAL.has(input)) return { input, prospeo: input, match: "exact" };
  const lower = OFFICIAL_LOWER.get(input.toLowerCase());
  if (lower) return { input, prospeo: lower, match: "exact" };
  const aliased = PROSPEO_INDUSTRY_ALIASES[input];
  if (aliased && OFFICIAL.has(aliased)) return { input, prospeo: aliased, match: "inexact" };
  const aliasedLower = Object.entries(PROSPEO_INDUSTRY_ALIASES).find(([from]) => from.toLowerCase() === input.toLowerCase());
  if (aliasedLower && OFFICIAL.has(aliasedLower[1])) return { input, prospeo: aliasedLower[1], match: "inexact" };
  const punct = punctuationForm(input);
  if (punct !== input && OFFICIAL.has(punct)) return { input, prospeo: punct, match: "inexact" };
  const punctLower = OFFICIAL_LOWER.get(punct.toLowerCase());
  if (punctLower) return { input, prospeo: punctLower, match: "inexact" };
  return { input, prospeo: null, match: "none" };
}

export function mapProspeoIndustries(names: readonly string[]): ProspeoIndustryMapping[] {
  return names.map(mapProspeoIndustry);
}
